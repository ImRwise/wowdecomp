#!/usr/bin/env python3
"""Writes Addons/EsteriaToolChest/ToolChestCatalog.lua: every synced Retail item (item_template entry >= 1000000) in the
form the GM Tool Chest's "Armor & Items" tab reads. Re-run after a sync.

    python Tools/ServerSync/export_toolchest_catalog.py [--mysql PATH] [--host 127.0.0.1] [--db acore_world]

One line per item: id|name|class|subclass|inventoryType|quality|itemLevel|requiredLevel|learnSpell
(learnSpell is the spell `.learn` teaches for mounts and companions, 0 otherwise)."""
import argparse, subprocess
from pathlib import Path

QUERY = """select entry, name, class, subclass, InventoryType, Quality, ItemLevel, RequiredLevel,
 if(spelltrigger_2 = 6, spellid_2, if(spelltrigger_1 = 6, spellid_1, 0))
 from item_template where entry >= 1000000 and name <> '' order by class, subclass, name, entry"""


def main():
    here = Path(__file__).resolve()
    ap = argparse.ArgumentParser()
    ap.add_argument("--mysql", default=r"C:\Program Files\MySQL\MySQL Server 8.0\bin\mysql.exe")
    ap.add_argument("--host", default="127.0.0.1")
    ap.add_argument("--user", default="root")
    ap.add_argument("--db", default="acore_world")
    ap.add_argument("--out", default=str(here.parents[2] / "Addons" / "EsteriaToolChest" / "ToolChestCatalog.lua"))
    args = ap.parse_args()
    raw = subprocess.run([args.mysql, "-u" + args.user, "--host=" + args.host, args.db, "-N", "-B", "-e", QUERY],
                         check=True, capture_output=True).stdout.decode("utf-8")
    lines = []
    for row in raw.splitlines():
        f = row.split("\t")
        if len(f) != 9:
            continue
        f[1] = f[1].replace("|", "/").replace("]==]", "]=]").strip()
        lines.append("|".join(f))
    body = "\n".join(lines)
    Path(args.out).write_text(
        "-- Generated by Tools/ServerSync/export_toolchest_catalog.py - do not edit.\n"
        "-- id|name|class|subclass|inventoryType|quality|itemLevel|requiredLevel|learnSpell\n"
        "EsteriaToolChestCatalog = [==[\n" + body + "\n]==]\n", encoding="utf-8", newline="\n")
    print("wrote %d items to %s" % (len(lines), args.out))


if __name__ == "__main__":
    main()
